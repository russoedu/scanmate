const GLYPH_WIDTH = 5
const GLYPH_HEIGHT = 7
/** Blank columns between one glyph and the next, in glyph pixels. */
const TRACKING = 1

export interface LabelOptions {
  /** Pixels per glyph pixel. Default `2`, which reads at arm's length on a page. */
  scale?: number
  /** Ink colour. Default black. */
  color?: readonly [number, number, number, number]
}

/** How wide and tall `text` will be at this scale, in pixels. */
export function labelSize (text: string, options: LabelOptions = {}): { width: number, height: number } {
  const scale = options.scale ?? 2

  return {
    width:  Math.max(0, [...text].length * (GLYPH_WIDTH + TRACKING) - TRACKING) * scale,
    height: GLYPH_HEIGHT * scale,
  }
}

/**
 * Draws a label with its top-left corner at `x`, `y`.
 *
 * @param raster - The image to draw on.
 * @param text - What to write; letters are drawn as capitals, and anything the
 *   font does not carry is drawn as a space.
 * @param at - Where the label's top-left corner goes.
 * @param options - Scale and colour.
 * @returns The box the label occupies.
 */
export function drawLabel (raster: Raster, text: string, at: { x: number, y: number }, options: LabelOptions = {}): Rect {
  const scale = Math.max(1, Math.round(options.scale ?? 2))
  const color = options.color ?? [0, 0, 0, 255]
  const left = Math.round(at.x)
  const top = Math.round(at.y)

  for (const [index, character] of [...text.toUpperCase()].entries()) {
    const glyph = GLYPHS[character] ?? GLYPHS[' ']
    const originX = left + index * (GLYPH_WIDTH + TRACKING) * scale

    for (const [row, bits] of glyph.entries())
      for (let column = 0; column < GLYPH_WIDTH; column++) {
        if ((bits & (1 << (GLYPH_WIDTH - 1 - column))) === 0) continue
        fillCell(raster, originX + column * scale, top + row * scale, scale, color)
      }
  }

  return { x: left, y: top, ...labelSize(text, { scale }) }
}

function fillCell (raster: Raster, x: number, y: number, scale: number, color: readonly [number, number, number, number]): void {
  for (let dy = 0; dy < scale; dy++) {
    const row = y + dy
    if (row < 0 || row >= raster.height) continue
    for (let dx = 0; dx < scale; dx++) {
      const column = x + dx
      if (column < 0 || column >= raster.width) continue
      const i = (row * raster.width + column) * 4
      raster.data[i] = color[0]
      raster.data[i + 1] = color[1]
      raster.data[i + 2] = color[2]
      raster.data[i + 3] = color[3]
    }
  }
}
