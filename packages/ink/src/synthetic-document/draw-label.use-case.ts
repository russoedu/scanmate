/**
 * Small labels drawn straight onto a raster, for legends and captions on an
 * evidence page.
 *
 * The glyphs are a 5x7 bitmap carried in this file. That is deliberate: a real
 * font means a font file to ship and license, or the host's fonts, and a
 * container with no fonts installed would silently draw nothing at all. A
 * legend that vanishes in production is worse than one that is plain.
 *
 * Letters are drawn as capitals whatever case they are given, since capitals
 * are all a 5x7 cell reads well at the sizes a label wants.
 */

